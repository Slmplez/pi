import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = resolve(repoRoot, "contracts/ascet-element-write-contract.json");
const tsPath = resolve(repoRoot, "packages/ascet-extension/src/generated/ascet-element-write-contract.generated.ts");
const csharpPath = resolve(repoRoot, "ascetcli/src/AscetCopilot/AscetElementWriteContract.Generated.cs");
const check = process.argv.includes("--check");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8").replace(/^\\uFEFF/u, ""));

function requireStringArray(value, path) {
  if (!Array.isArray(value) || value.length === 0 || value.some((entry) => typeof entry !== "string" || entry.length === 0)) {
    throw new Error(`${path} must be a non-empty string array.`);
  }
  if (new Set(value).size !== value.length) throw new Error(`${path} contains duplicate values.`);
  return value;
}

const intents = requireStringArray(manifest.intents, "intents");
const kinds = requireStringArray(manifest.kinds, "kinds");
const scopes = requireStringArray(manifest.scopes, "scopes");
if (!manifest.roles || typeof manifest.roles !== "object" || Array.isArray(manifest.roles)) throw new Error("roles must be an object.");
const roles = Object.keys(manifest.roles);
requireStringArray(roles, "roles");
for (const role of roles) {
  const definition = manifest.roles[role];
  if (!definition || typeof definition !== "object" || Array.isArray(definition)) throw new Error(`roles.${role} must be an object.`);
  if (definition.requiredKind !== null && !kinds.includes(definition.requiredKind)) throw new Error(`roles.${role}.requiredKind is invalid.`);
  if (definition.requiredScope !== null && !scopes.includes(definition.requiredScope)) throw new Error(`roles.${role}.requiredScope is invalid.`);
  requireStringArray(definition.forbiddenFields.length === 0 ? ["__empty__"] : definition.forbiddenFields, `roles.${role}.forbiddenFields`);
  requireStringArray(definition.requiredCreateFields, `roles.${role}.requiredCreateFields`);
}
for (const fieldGroup of ["root", "element", "normalizedElement", "data", "implementation", "range"]) {
  requireStringArray(manifest.fields?.[fieldGroup], `fields.${fieldGroup}`);
}
const canonical = JSON.stringify(manifest);
const contractHash = createHash("sha256").update(canonical).digest("hex");
const json = (value) => JSON.stringify(value, null, "\t");
const generatedHeader = "// Generated by scripts/generate-ascet-element-write-contract.mjs. Do not edit.\n";
const ts = `${generatedHeader}
export const ascetElementWriteContractVersion = ${JSON.stringify(manifest.version)} as const;
export const ascetElementWriteContractHash = ${JSON.stringify(contractHash)} as const;
export const ascetApplyElementIntentValues = ${json(intents)} as const;
export const ascetElementKindValues = ${json(kinds)} as const;
export const ascetElementScopeValues = ${json(scopes)} as const;
export const ascetElementRoleValues = ${json(roles)} as const;
export const ascetElementRoleContract = ${json(manifest.roles)} as const;
export const ascetElementSpecRootFields = ${json(manifest.fields.root)} as const;
export const ascetElementSpecFields = ${json(manifest.fields.element)} as const;
export const ascetNormalizedElementSpecFields = ${json(manifest.fields.normalizedElement)} as const;
export const ascetElementDataFields = ${json(manifest.fields.data)} as const;
export const ascetElementImplementationFields = ${json(manifest.fields.implementation)} as const;
export const ascetElementRangeFields = ${json(manifest.fields.range)} as const;

export const ascetElementWriteContractMetadata = {
	version: ascetElementWriteContractVersion,
	hash: ascetElementWriteContractHash,
	intents: ascetApplyElementIntentValues,
	kinds: ascetElementKindValues,
	scopes: ascetElementScopeValues,
	roles: ascetElementRoleContract,
	fields: {
		root: ascetElementSpecRootFields,
		element: ascetElementSpecFields,
		normalizedElement: ascetNormalizedElementSpecFields,
		data: ascetElementDataFields,
		implementation: ascetElementImplementationFields,
		range: ascetElementRangeFields,
	},
} as const;
`;
const csharpArray = (name, values) => `    public static readonly string[] ${name} = new string[] { ${values.map((value) => JSON.stringify(value)).join(", ")} };`;
const biomeBin =
  process.platform === "win32"
    ? resolve(repoRoot, "node_modules", "@biomejs", "cli-win32-x64", "biome.exe")
    : resolve(repoRoot, "node_modules", ".bin", "biome");
const formatted = spawnSync(biomeBin, ["format", "--stdin-file-path", tsPath], {
  input: ts,
  encoding: "utf8",
});
if (formatted.status !== 0 || !formatted.stdout) {
  throw new Error(`Failed to format generated TypeScript contract: ${formatted.stderr || "unknown Biome error"}`);
}
const formattedTs = formatted.stdout;
const csharp = `${generatedHeader}using System;

public static class AscetElementWriteContract
{
    public const int Version = ${manifest.version};
    public const string ContractSha256 = ${JSON.stringify(contractHash)};
${csharpArray("IntentValues", intents)}
${csharpArray("KindValues", kinds)}
${csharpArray("ScopeValues", scopes)}
${csharpArray("RoleValues", roles)}
${csharpArray("RootFields", manifest.fields.root)}
${csharpArray("ElementFields", manifest.fields.element)}
${csharpArray("NormalizedElementFields", manifest.fields.normalizedElement)}
${csharpArray("DataFields", manifest.fields.data)}
${csharpArray("ImplementationFields", manifest.fields.implementation)}
${csharpArray("RangeFields", manifest.fields.range)}
}
`;

let failed = false;
for (const [path, expected] of [[tsPath, formattedTs], [csharpPath, csharp]]) {
  if (check) {
    let actual = "";
    try { actual = readFileSync(path, "utf8").replace(/\r\n/g, "\n"); } catch {}
    if (actual !== expected) {
      console.error(`Generated ASCET element-write contract is stale: ${path}`);
      failed = true;
    }
  } else {
    writeFileSync(path, expected, "utf8");
    console.log(`Generated ${path}`);
  }
}
if (failed) process.exitCode = 1;
